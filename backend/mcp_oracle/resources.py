@mcp.resource("openapi://full")
def openapi_full() -> str:
    """Complete OpenAPI 3.1 specification for the entire API.

    Auto-generated by FastAPI from the running application. Includes every
    route, parameter, request body, response schema, and error code.
    Refreshes automatically when endpoints are added or modified — just
    restart the service.

    This is the single source of truth for the API surface. Use it to
    discover every available endpoint and its exact parameter types.
    """
    from main import app
    return json.dumps(app.openapi(), indent=2)


@mcp.resource("openapi://endpoints")
def openapi_endpoints() -> str:
    """Condensed endpoint index: one line per route.

    Format: ``METHOD path — summary``
    Sorted alphabetically by path. Useful for quick scanning of the
    full API surface without parsing the complete OpenAPI spec.
    """
    from main import app
    spec = app.openapi()
    lines: list[str] = ["# API Endpoint Index", ""]
    for path in sorted(spec.get("paths", {})):
        for method, details in spec["paths"][path].items():
            if method.startswith("x-"):
                continue
            summary = details.get("summary", "")
            tag = (details.get("tags") or [""])[0]
            lines.append(f"- **{method.upper()}** `{path}` — {summary} _({tag})_")
    lines.append(f"\n**Total:** {len(lines) - 2} endpoints")
    return "\n".join(lines)


