"""Phase 2: Auto-synced MCP Resources.

Each resource reads from a LIVE source — FastAPI's app.openapi(), the
filesystem (markdown docs), or runtime introspection (Pydantic models,
provider config). No caching, no manual sync. When code changes, the
next resource query returns fresh data.

All resources are read-only. None make HTTP calls, none write to DB,
none have side effects.
"""

from __future__ import annotations

import glob
import json
import os
from pathlib import Path

from .server import mcp

_DOCS_DIR = Path(__file__).resolve().parent.parent.parent / "docs"


def _latest_doc_file(pattern: str) -> Path | None:
    """Find the newest dated markdown file matching the pattern."""
    files = sorted(_DOCS_DIR.glob(pattern))
    return files[-1] if files else None


