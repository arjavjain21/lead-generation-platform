@mcp.resource("schemas://{model_name}")
def get_schema(model_name: str) -> str:
    """JSON schema for any Pydantic request model.

    Returns the full ``model_json_schema()`` output — every field, type,
    default, and validation rule. Useful for constructing valid API
    requests without guessing parameter names.

    Available models:
    - ``UnifiedEnrichRequest`` — POST /api/enrichment/enrich
    - ``StartJobRequest`` — POST /api/enrichment/jobs (legacy)
    - ``ProviderToggleRequest`` — POST /api/enrichment/flows/domain-enrich
    - ``LinkedInV2Request`` — POST /api/enrichment/by-linkedin-v2
    - ``CompanySearchRequest`` — POST /api/enrichment/search/companies

    Args:
        model_name: The Pydantic class name (case-sensitive).
    """
    from enrichment import routes as enr

    model_map = {
        "UnifiedEnrichRequest": enr.UnifiedEnrichRequest,
        "StartJobRequest": enr.StartJobRequest,
        "ProviderToggleRequest": enr.ProviderToggleRequest,
        "LinkedInV2Request": enr.LinkedInV2Request,
        "CompanySearchRequest": enr.CompanySearchRequest,
    }

    if model_name not in model_map:
        available = "\n".join(f"  - `{n}`" for n in sorted(model_map))
        return f"Unknown model `{model_name}`.\n\nAvailable models:\n{available}"

    schema = model_map[model_name].model_json_schema()
    return json.dumps(schema, indent=2)
